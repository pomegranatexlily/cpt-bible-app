import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const code=fs.readFileSync("oustory-calendar.js","utf8");
const ctx={window:{},Date,Intl};
vm.runInNewContext(code,ctx,{filename:"oustory-calendar.js"});
const cal=ctx.window.OustoryCalendar;
assert.ok(cal);
const archive=JSON.parse(fs.readFileSync("calendar/archive.json","utf8"));
const [xal,lunar]=archive.sources;
const xe=cal.normalize(xal),le=cal.normalize(lunar);
assert.equal(xe.length,152);
assert.equal(le.filter(e=>e.type==="new-moon").length,11);
assert.equal(le.filter(e=>e.type==="sabbath").length,44);
assert.equal(le.filter(e=>e.type==="feast").length,4);
const xd=cal.dailyIndex(xe),ld=cal.dailyIndex(le);
assert.ok(xd.get("2025-08-22").some(e=>e.subject==="Feast of Trumpets"));
assert.equal(ld.get("2025-09-22").filter(e=>e.subject==="Trumpets").length,1);
assert.ok(ld.get("2025-10-06").some(e=>e.subject==="Feast of Tabernacles"));
assert.ok(ld.get("2025-10-13").some(e=>e.subject==="Feast of Tabernacles"));
assert.ok(ld.get("2025-11-28").some(e=>e.subject==="Feast of Dedication"));
assert.ok(ld.get("2025-12-05").some(e=>e.subject==="Feast of Dedication"));
assert.ok(xd.get("2025-04-26").some(e=>e.type==="new-moon"));
assert.ok(xd.get("2025-04-26").some(e=>e.type==="sabbath"));
assert.ok(!xd.has("2026-10-17"),"No future dates may be invented");
const aug=cal.calendarCells(2025,7);
assert.equal(aug.length%7,0);
assert.equal(aug[0].iso,"2025-07-27");
assert.equal(aug.filter(e=>e.inMonth).length,31);
assert.equal(aug[5].iso,"2025-08-01");
const feb=cal.calendarCells(2026,1);
assert.equal(feb.filter(e=>e.inMonth).length,28);
const leap=cal.calendarCells(2028,1);
assert.equal(leap.filter(e=>e.inMonth).length,29);
console.log("PASS: calendar source fidelity, feast ranges, double observances, 7-column grid, leap year, no future extrapolation.");
